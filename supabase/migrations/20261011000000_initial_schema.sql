-- Creates a profile row when a user signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
as $function$
begin
  insert into public.profiles (
    id,
    first_name,
    last_name,
    username,
    created_at
  )
  values (
    new.id,
    new.raw_user_meta_data->>'firstname',
    new.raw_user_meta_data->>'lastname',
    lower(
      coalesce(new.raw_user_meta_data->>'firstname', '')
      || coalesce(new.raw_user_meta_data->>'lastname', '')
      || substring(gen_random_uuid()::text, 1, 8)
    ),
    now()
  );
  return new;
end;
$function$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.approve_claim_request(p_claim_id bigint, p_item_id bigint)
returns json
language plpgsql
as $function$
DECLARE
  v_result JSON;
  v_affected_rows INTEGER;
BEGIN
  -- Start implicit transaction (functions are atomic by default)

  -- 1. Approve the selected claim
  UPDATE claims
  SET
    status = 'approved',
    updated_at = NOW()
  WHERE
    id = p_claim_id
    AND item_id = p_item_id
    AND status = 'pending';

  GET DIAGNOSTICS v_affected_rows = ROW_COUNT;

  -- Check if the approval was successful
  IF v_affected_rows = 0 THEN
    RAISE EXCEPTION 'Claim not found or already processed';
  END IF;

  -- 2. Reject all other pending claims for this item
  UPDATE claims
  SET
    status = 'rejected',
    updated_at = NOW()
  WHERE
    item_id = p_item_id
    AND id != p_claim_id
    AND status = 'pending';

  -- 3. Optionally update the item status
  UPDATE items
  SET
    status = 'reserved',
    claimed_by = (SELECT user_id FROM claims WHERE id = p_claim_id),
    updated_at = NOW()
  WHERE id = p_item_id;

  -- Return success result
  v_result := json_build_object(
    'success', true,
    'approved_claim_id', p_claim_id,
    'message', 'Claim approved successfully'
  );

  RETURN v_result;

EXCEPTION
  WHEN OTHERS THEN
    -- Any error will rollback the entire transaction
    RAISE EXCEPTION 'Transaction failed: %', SQLERRM;
END;
$function$;

create or replace function public.mark_claim_cancel_request(p_claim_id bigint, p_item_id bigint)
returns json
language plpgsql
as $function$
DECLARE
  v_result JSON;
  v_affected_rows INTEGER;
BEGIN
  -- Start implicit transaction (functions are atomic by default)

  -- 1. reject the selected claim
  UPDATE claims
  SET
    status = 'rejected',
    updated_at = NOW()
  WHERE
    id = p_claim_id
    AND item_id = p_item_id
    AND status = 'approved';

  GET DIAGNOSTICS v_affected_rows = ROW_COUNT;

  -- Check if the cancelation was successful
  IF v_affected_rows = 0 THEN
    RAISE EXCEPTION 'Claim not found or already processed';
  END IF;

  -- 2. update the item status
  UPDATE items
  SET
    status = 'available',
    claimed_by = null,
    updated_at = NOW()
  WHERE id = p_item_id;

  -- Return success result
  v_result := json_build_object(
    'success', true,
    'approved_claim_id', p_claim_id,
    'message', 'Claim cancelled successfully'
  );

  RETURN v_result;

EXCEPTION
  WHEN OTHERS THEN
    -- Any error will rollback the entire transaction
    RAISE EXCEPTION 'Transaction failed: %', SQLERRM;
END;
$function$;

