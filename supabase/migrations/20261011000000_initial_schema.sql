-- profiles
create policy "Profiles are viewable by everyone"
  on public.profiles for select
  to anon, authenticated
  using (true);

create policy "Users can insert their own profile"
  on public.profiles for insert
  to authenticated
  with check (auth.uid() = id);

create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- items
create policy "Enable read access for all users"
  on public.items for select
  to public
  using (deleted_at is null);

create policy "Owners can read their items"
  on public.items for select
  to authenticated
  using (user_id = auth.uid());

create policy "Enable insert for authenticated users only"
  on public.items for insert
  to authenticated
  with check (user_id = auth.uid());

create policy "Items update by owner"
  on public.items for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- claims
create policy "claimant can read own claims"
  on public.claims for select
  to authenticated
  using (auth.uid() = user_id);

create policy "Owners can see claims for their items"
  on public.claims for select
  to authenticated
  using (exists (
    select 1 from public.items
    where items.id = claims.item_id and items.user_id = auth.uid()
  ));

create policy "Users can create claims"
  on public.claims for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "user owner can update the claim status approve reject request"
  on public.claims for update
  to authenticated
  using (
    status = any (array['pending'::text, 'approved'::text])
    and exists (
      select 1 from public.items
      where items.id = claims.item_id and items.user_id = auth.uid()
    )
  )
  with check (status = any (array['approved'::text, 'rejected'::text]));

