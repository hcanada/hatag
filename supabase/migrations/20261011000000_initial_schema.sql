create table public.profiles (
  id uuid not null,
  username text,
  city text,
  barangay text,
  bio text,
  verified boolean default false,
  created_at timestamptz default now(),
  first_name text not null,
  last_name text not null,
  constraint profiles_pkey primary key (id),
  constraint profiles_username_key unique (username),
  constraint profiles_id_fkey foreign key (id) references auth.users (id) on delete cascade
);

create table public.items (
  id bigint generated by default as identity not null,
  user_id uuid not null,
  title text not null,
  description text,
  category text,
  images text[],
  city text,
  barangay text,
  status text default 'available'::text,
  created_at timestamptz default now(),
  claimed_by uuid,
  updated_at timestamptz,
  deleted_at timestamptz,
  constraint items_pkey primary key (id),
  constraint items_status_check check (status = any (array['available'::text, 'reserved'::text, 'claimed'::text])),
  constraint items_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade,
  constraint items_user_id_fkey1 foreign key (user_id) references public.profiles (id) on delete cascade,
  constraint items_claimed_by_fkey foreign key (claimed_by) references auth.users (id)
);

create table public.claims (
  id bigint generated always as identity not null,
  item_id bigint not null,
  user_id uuid not null,
  status text not null,
  created_at timestamptz default now(),
  updated_at timestamptz,
  constraint claims_pkey primary key (id),
  constraint claims_status_check check (status = any (array['pending'::text, 'approved'::text, 'rejected'::text])),
  constraint claims_item_id_fkey foreign key (item_id) references public.items (id) on delete cascade,
  constraint claims_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade,
  constraint claims_user_id_fkey1 foreign key (user_id) references public.profiles (id) on delete cascade
);

-- A user can have only one active (pending/approved) claim per item.
create unique index claims_unique_user_item on public.claims using btree (item_id, user_id)
  where (status = any (array['pending'::text, 'approved'::text]));

-- An item can have only one approved claim.
create unique index one_approved_claim_per_item on public.claims using btree (item_id)
  where (status = 'approved'::text);

